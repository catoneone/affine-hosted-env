"""Node boot script (architecture v2): what a fresh machine runs once to become a sandbox node.

Steps, from internal experiment EXP-017 (k3s v1.36.5 on boat and Targon machines):
1. Firewall. boat machines run ufw with incoming denied, and snapshots do not keep rules, so the cluster CIDRs
   (and the WireGuard port, if any) are allowed on every boot.
2. gVisor. `runsc` from the gVisor apt repository, plus a containerd drop-in that registers the `runsc` runtime
   for k3s (`config-v3.toml.d/runsc.toml`). Pods ask for it with `runtimeClassName: gvisor`.
3. WireGuard port. flannel `wireguard-native` advertises its listen port to the other nodes, so on a provider that
   remaps ports (Targon SHARED networking) the listen port must equal the public port, and traffic arriving on
   the forwarded internal port is redirected to it.
4. k3s agent. Joins with outbound connections only; the server tunnels kubelet traffic back over them.

The join token is passed in the environment of the installer only. The script deletes itself first, never runs
with `set -x`, and logs to a root-only file, so the token is not left readable on disk outside k3s's own
root-only environment file.
"""
from __future__ import annotations

import json
import re
import shlex

K3S_VERSION = 'v1.36.5+k3s1'          # the version EXP-017 ran; pin, do not follow a moving channel
CLUSTER_CIDRS = ('10.42.0.0/16', '10.43.0.0/16')
CONTAINERD_DROPIN = '/var/lib/rancher/k3s/agent/etc/containerd/config-v3.toml.d/runsc.toml'
_LABEL = re.compile(r'^[A-Za-z0-9]([A-Za-z0-9._/-]{0,251}[A-Za-z0-9])?$')


def _check_label(k: str, v: str) -> None:
    if not _LABEL.match(k) or (v and not _LABEL.match(v)) or len(v) > 63:
        raise ValueError(f'bad node label {k}={v}')


def render_boot_script(*, server_url: str, join_token: str, labels: dict | None = None, node_name: str | None = None,
                       wireguard_port: int | None = None, wireguard_forwarded_port: int | None = None,
                       gvisor: bool = True, k3s_version: str = K3S_VERSION) -> str:
    """server_url: https://<control plane>:<port> as reachable from the node.
    wireguard_port: the public UDP port other nodes must use to reach this node (flannel listens on it).
    wireguard_forwarded_port: the port the provider actually delivers that traffic to inside the VM, when it
    differs (Targon remaps); it is redirected to wireguard_port."""
    labels = dict(labels or {})
    for k, v in labels.items():
        _check_label(k, str(v))
    if not re.match(r'^https://[^\s\'"]+$', server_url):
        raise ValueError(f'bad server url {server_url!r}')
    q = shlex.quote
    args = ['agent', *[x for k, v in sorted(labels.items()) for x in ('--node-label', f'{k}={v}')]]
    if node_name:
        args += ['--node-name', node_name]

    lines = [
        '#!/usr/bin/env bash',
        '# hosted-env node boot script (generated by hosted_env.providers.machine.bootstrap). Runs once as root.',
        'set -euo pipefail',
        'rm -f -- "$0" || true                       # the script carries the join token',
        'umask 077',
        'mkdir -p /var/log/hosted-env /var/lib/hosted-env',
        'exec >>/var/log/hosted-env/boot.log 2>&1',
        'echo "boot start $(date -u +%FT%TZ)"',
        '',
        '# 1. firewall: re-applied on every boot (snapshots drop ufw rules)',
        "if command -v ufw >/dev/null && ufw status | grep -q 'Status: active'; then",
        *[f'  ufw allow from {c} >/dev/null' for c in CLUSTER_CIDRS],
    ]
    if wireguard_port:
        lines.append(f'  ufw allow {int(wireguard_port)}/udp >/dev/null')
        if wireguard_forwarded_port and wireguard_forwarded_port != wireguard_port:
            lines.append(f'  ufw allow {int(wireguard_forwarded_port)}/udp >/dev/null')
    lines += ['fi', '']
    if gvisor:
        lines += [
            '# 2. gVisor runtime for Pods with runtimeClassName: gvisor',
            'export DEBIAN_FRONTEND=noninteractive',
            'curl -fsSL https://gvisor.dev/archive.key | gpg --batch --yes --dearmor '
            '-o /usr/share/keyrings/gvisor-archive-keyring.gpg',
            'echo "deb [arch=$(dpkg --print-architecture) signed-by=/usr/share/keyrings/gvisor-archive-keyring.gpg] '
            'https://storage.googleapis.com/gvisor/releases release main" > /etc/apt/sources.list.d/gvisor.list',
            'apt-get update -qq',
            'apt-get install -y -qq runsc',
            f'mkdir -p {q(CONTAINERD_DROPIN.rsplit("/", 1)[0])}',
            f"cat > {q(CONTAINERD_DROPIN)} <<'EOF'",
            "[plugins.'io.containerd.cri.v1.runtime'.containerd.runtimes.runsc]",
            '  runtime_type = "io.containerd.runsc.v1"',
            'EOF',
            '',
        ]
    if wireguard_port:
        conf = {'Network': '10.42.0.0/16', 'EnableIPv4': True, 'EnableIPv6': False,
                'Backend': {'Type': 'wireguard', 'ListenPort': int(wireguard_port), 'PersistentKeepaliveInterval': 25}}
        lines += [
            '# 3. flannel WireGuard listens on the public port (providers that remap ports need this)',
            'mkdir -p /etc/rancher/k3s',
            "cat > /etc/rancher/k3s/flannel.json <<'EOF'",
            json.dumps(conf),
            'EOF',
        ]
        if wireguard_forwarded_port and wireguard_forwarded_port != wireguard_port:
            lines.append(f'iptables -t nat -C PREROUTING -p udp --dport {int(wireguard_forwarded_port)} -j REDIRECT '
                         f'--to-ports {int(wireguard_port)} 2>/dev/null || iptables -t nat -I PREROUTING -p udp '
                         f'--dport {int(wireguard_forwarded_port)} -j REDIRECT --to-ports {int(wireguard_port)}')
        args += ['--flannel-conf', '/etc/rancher/k3s/flannel.json']
        lines.append('')
    lines += [
        '# 4. k3s agent (outbound only; the token goes to the installer environment, never to the log)',
        f'curl -sfL https://get.k3s.io | INSTALL_K3S_VERSION={q(k3s_version)} K3S_URL={q(server_url)} '
        f'K3S_TOKEN={q(join_token)} sh -s - {" ".join(q(a) for a in args)} >/dev/null',
        'touch /var/lib/hosted-env/booted',
        'echo "boot done $(date -u +%FT%TZ)"',
    ]
    return '\n'.join(lines) + '\n'
