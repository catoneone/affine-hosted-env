"""Boot scripts (architecture v2): what a fresh machine runs once to become a sandbox node or the control plane.

Steps, from internal experiment EXP-017 (k3s v1.36.5 on boat and Targon machines):
1. Firewall. boat machines run ufw with incoming denied, and snapshots do not keep rules, so the cluster CIDRs
   (and the WireGuard port, if any) are allowed on every boot.
2. gVisor. `runsc` from the gVisor apt repository, plus a containerd drop-in that registers the `runsc` runtime
   for k3s (`config-v3.toml.d/runsc.toml`). Pods ask for it with `runtimeClassName: gvisor`.
3. WireGuard port. flannel `wireguard-native` advertises its listen port to the other nodes, so on a provider that
   remaps ports (Targon SHARED networking) the listen port must equal the public port, and traffic arriving on
   the forwarded internal port is redirected to it.
4. k3s agent. Joins with outbound connections only; the server tunnels kubelet traffic back over them.

The join token is passed in the environment of the installer only. The script deletes itself first, never runs
with `set -x`, and logs to a root-only file, so the token is not left readable on disk outside k3s's own
root-only environment file.

`render_server_boot_script` sets up the k3s server. On Targon SHARED networking (EXP-017 round 3) the API port is
remapped and the VM cannot reach its own public address, so the server advertises the public IP and port, the
public IP is added to `lo`, and socat forwards it to the local API port (`hairpin=True`).
"""
from __future__ import annotations

import ipaddress
import json
import re
import shlex

K3S_VERSION = 'v1.36.5+k3s1'          # the version EXP-017 ran; pin, do not follow a moving channel
CLUSTER_CIDRS = ('10.42.0.0/16', '10.43.0.0/16')
CONTAINERD_DROPIN = '/var/lib/rancher/k3s/agent/etc/containerd/config-v3.toml.d/runsc.toml'
_LABEL = re.compile(r'^[A-Za-z0-9]([A-Za-z0-9._/-]{0,251}[A-Za-z0-9])?$')


def _check_label(k: str, v: str) -> None:
    if not _LABEL.match(k) or (v and not _LABEL.match(v)) or len(v) > 63:
        raise ValueError(f'bad node label {k}={v}')


def _header(kind: str) -> list[str]:
    return [
        '#!/usr/bin/env bash',
        f'# hosted-env {kind} boot script (generated by hosted_env.providers.machine.bootstrap). Runs once as root.',
        'set -euo pipefail',
        'rm -f -- "$0" || true                       # the script carries the join token',
        'umask 077',
        'mkdir -p /var/log/hosted-env /var/lib/hosted-env',
        'exec >>/var/log/hosted-env/boot.log 2>&1',
        'echo "boot start $(date -u +%FT%TZ)"',
        'export DEBIAN_FRONTEND=noninteractive',
        '',
    ]


def _udp_ports(wireguard_port: int | None, forwarded: int | None) -> list[int]:
    if not wireguard_port:
        return []
    return [int(wireguard_port)] + ([int(forwarded)] if forwarded and forwarded != wireguard_port else [])


def _firewall(tcp: list[int], udp: list[int]) -> list[str]:
    return [
        '# firewall: re-applied on every boot (snapshots drop ufw rules)',
        "if command -v ufw >/dev/null && ufw status | grep -q 'Status: active'; then",
        *[f'  ufw allow from {c} >/dev/null' for c in CLUSTER_CIDRS],
        *[f'  ufw allow {int(p)}/tcp >/dev/null' for p in tcp],
        *[f'  ufw allow {int(p)}/udp >/dev/null' for p in udp],
        'fi',
        '',
    ]


def _gvisor() -> list[str]:
    q = shlex.quote
    return [
        '# gVisor runtime for Pods with runtimeClassName: gvisor',
        'curl -fsSL https://gvisor.dev/archive.key | gpg --batch --yes --dearmor '
        '-o /usr/share/keyrings/gvisor-archive-keyring.gpg',
        'echo "deb [arch=$(dpkg --print-architecture) signed-by=/usr/share/keyrings/gvisor-archive-keyring.gpg] '
        'https://storage.googleapis.com/gvisor/releases release main" > /etc/apt/sources.list.d/gvisor.list',
        'apt-get update -qq',
        'apt-get install -y -qq runsc',
        f'mkdir -p {q(CONTAINERD_DROPIN.rsplit("/", 1)[0])}',
        f"cat > {q(CONTAINERD_DROPIN)} <<'EOF'",
        "[plugins.'io.containerd.cri.v1.runtime'.containerd.runtimes.runsc]",
        '  runtime_type = "io.containerd.runsc.v1"',
        'EOF',
        '',
    ]


def _redirect(forwarded: int, port: int) -> str:
    rule = f'PREROUTING -p udp --dport {int(forwarded)} -j REDIRECT --to-ports {int(port)}'
    return f'iptables -t nat -C {rule} 2>/dev/null || iptables -t nat -I {rule}'


def _flannel(wireguard_port: int | None, forwarded: int | None, redirect_now: bool = True) -> tuple[list[str], list]:
    """flannel WireGuard listens on the public port: it advertises its listen port to the other nodes, so on a
    provider that remaps ports the two must be equal. The whole cluster uses the same ListenPort."""
    if not wireguard_port:
        return [], []
    conf = {'Network': CLUSTER_CIDRS[0], 'EnableIPv4': True, 'EnableIPv6': False,
            'Backend': {'Type': 'wireguard', 'ListenPort': int(wireguard_port), 'PersistentKeepaliveInterval': 25}}
    lines = [
        '# flannel WireGuard listens on the public port (providers that remap ports need this)',
        'mkdir -p /etc/rancher/k3s',
        "cat > /etc/rancher/k3s/flannel.json <<'EOF'",
        json.dumps(conf),
        'EOF',
    ]
    if redirect_now and forwarded and forwarded != wireguard_port:
        lines.append(_redirect(forwarded, wireguard_port))
    return lines + [''], ['--flannel-conf', '/etc/rancher/k3s/flannel.json']


def render_boot_script(*, server_url: str, join_token: str, labels: dict | None = None, node_name: str | None = None,
                       wireguard_port: int | None = None, wireguard_forwarded_port: int | None = None,
                       gvisor: bool = True, k3s_version: str = K3S_VERSION) -> str:
    """Agent (sandbox node) boot script.
    server_url: https://<control plane>:<port> as reachable from the node.
    wireguard_port: the cluster-wide flannel WireGuard port (the control plane's public UDP port).
    wireguard_forwarded_port: the port the provider actually delivers that traffic to inside the VM, when it
    differs (Targon remaps); it is redirected to wireguard_port."""
    labels = dict(labels or {})
    for k, v in labels.items():
        _check_label(k, str(v))
    if not re.match(r'^https://[^\s\'"]+$', server_url):
        raise ValueError(f'bad server url {server_url!r}')
    q = shlex.quote
    args = ['agent', *[x for k, v in sorted(labels.items()) for x in ('--node-label', f'{k}={v}')]]
    if node_name:
        args += ['--node-name', node_name]
    lines = _header('node') + _firewall([], _udp_ports(wireguard_port, wireguard_forwarded_port))
    if gvisor:
        lines += _gvisor()
    flannel, fargs = _flannel(wireguard_port, wireguard_forwarded_port)
    lines += flannel
    args += fargs
    lines += [
        '# k3s agent (outbound only; the token goes to the installer environment, never to the log)',
        f'curl -sfL https://get.k3s.io | INSTALL_K3S_VERSION={q(k3s_version)} K3S_URL={q(server_url)} '
        f'K3S_TOKEN={q(join_token)} sh -s - {" ".join(q(a) for a in args)} >/dev/null',
        'touch /var/lib/hosted-env/booted',
        'echo "boot done $(date -u +%FT%TZ)"',
    ]
    return '\n'.join(lines) + '\n'


def render_server_boot_script(*, join_token: str, public_ip: str, api_port: int = 6443, hairpin: bool = False,
                              wireguard_port: int | None = None, wireguard_forwarded_port: int | None = None,
                              node_name: str | None = None, schedulable: bool = False, gvisor: bool = True,
                              namespace: str = 'hosted-env', k3s_version: str = K3S_VERSION) -> str:
    """Control-plane (k3s server) boot script.
    public_ip / api_port: the address nodes and clients use to reach the API (Targon remaps 6443, e.g. to 20004).
    hairpin: the VM cannot reach its own public address (Targon SHARED); add it to lo and forward it locally.
    wireguard_port / wireguard_forwarded_port: as for nodes; the cluster-wide WireGuard port is this machine's
    public UDP port. schedulable=False taints the server so sandboxes run on nodes only."""
    ip = str(ipaddress.ip_address(public_ip))
    if not re.match(r'^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$', namespace):
        raise ValueError(f'bad namespace {namespace!r}')
    api_port = int(api_port)
    q = shlex.quote
    args = ['server', '--advertise-address', ip, '--advertise-port', str(api_port), '--tls-san', ip,
            '--node-external-ip', ip, '--disable', 'traefik', '--disable', 'servicelb',
            '--write-kubeconfig-mode', '0600']
    if not schedulable:
        args += ['--node-taint', 'node-role.kubernetes.io/control-plane=true:NoSchedule']
    if node_name:
        args += ['--node-name', node_name]
    udp = _udp_ports(wireguard_port, wireguard_forwarded_port)
    lines = _header('control-plane') + _firewall(sorted({6443, api_port}), udp)
    if gvisor:
        lines += _gvisor()
    flannel, fargs = _flannel(wireguard_port, wireguard_forwarded_port, redirect_now=not hairpin)
    lines += flannel
    args += fargs
    if hairpin:
        pre = [f'ExecStartPre=-/usr/sbin/ip addr add {ip}/32 dev lo']
        if len(udp) == 2:
            pre.append(f"ExecStartPre=/bin/sh -c '{_redirect(udp[1], udp[0])}'")
        lines += [
            '# hairpin: no route to our own public address, so serve it locally (survives reboots as a unit)',
            'apt-get update -qq',
            'apt-get install -y -qq socat',
            "cat > /etc/systemd/system/hosted-env-net.service <<'EOF'",
            '[Unit]',
            'Description=hosted-env hairpin to the public API address and WireGuard port redirect',
            'After=network-online.target',
            'Wants=network-online.target',
            'Before=k3s.service',
            '',
            '[Service]',
            *pre,
            f'ExecStart=/usr/bin/socat TCP-LISTEN:{api_port},bind={ip},reuseaddr,fork TCP:127.0.0.1:6443',
            'Restart=always',
            'RestartSec=2',
            '',
            '[Install]',
            'WantedBy=multi-user.target',
            'EOF',
            'systemctl daemon-reload',
            'systemctl enable --now hosted-env-net.service',
            '',
        ]
    manifests = [f'apiVersion: v1\nkind: Namespace\nmetadata:\n  name: {namespace}']
    if gvisor:
        manifests.append('apiVersion: node.k8s.io/v1\nkind: RuntimeClass\nmetadata:\n  name: gvisor\nhandler: runsc')
    lines += [
        '# k3s server (the token goes to the installer environment, never to the log)',
        f'curl -sfL https://get.k3s.io | INSTALL_K3S_VERSION={q(k3s_version)} K3S_TOKEN={q(join_token)} '
        f'sh -s - {" ".join(q(a) for a in args)} >/dev/null',
        'for _ in $(seq 1 60); do k3s kubectl get --raw=/readyz >/dev/null 2>&1 && break; sleep 5; done',
        "k3s kubectl apply -f - <<'EOF'",
        '\n---\n'.join(manifests),
        'EOF',
        'touch /var/lib/hosted-env/booted',
        'echo "boot done $(date -u +%FT%TZ)"',
    ]
    return '\n'.join(lines) + '\n'
